def by_id() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for spec in FIXTURES:
        if spec.get("same_as"):
            base = dict(next(s for s in FIXTURES if s["id"] == spec["same_as"]))
            base.update({k: v for k, v in spec.items() if k != "same_as"})
            base.pop("layout_checks", None)
            spec = base
        out[spec["id"]] = spec
    return out
